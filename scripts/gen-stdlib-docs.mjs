#!/usr/bin/env node
/**
 * Regenerate the signature reference in docs/stdlib.md from the real modules.
 *
 * Hand-maintained API tables drift. This one is read out of the actual export
 * tables, so the documentation cannot claim a function that does not exist, or
 * miss one that does.
 *
 * Everything between the two marker comments is replaced; prose outside them is
 * left alone.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

import { showSignature, signatureTy } from '../packages/core/dist/index.js';
import { STD_MODULES, createInterpreter } from '../packages/stdlib/dist/index.js';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DOC = path.join(ROOT, 'docs', 'stdlib.md');
const BEGIN = '<!-- BEGIN GENERATED REFERENCE -->';
const END = '<!-- END GENERATED REFERENCE -->';
const PRELUDE_BEGIN = '<!-- BEGIN GENERATED PRELUDE -->';
const PRELUDE_END = '<!-- END GENERATED PRELUDE -->';

/**
 * Render one export as a Lumen-looking signature.
 *
 * The declared one when there is one, which is already written in exactly this
 * syntax — so the reference says `upper(s: Str) -> Str` rather than `upper(s)`,
 * and says it because the library says it, not because somebody typed it here.
 * Anything not yet typed falls back to its parameter names, which is what all
 * of these looked like before.
 */
function signature(name, value) {
  if (value.k !== 'native') return name + ': ' + value.k;
  if (value.variadic === true) return name + '(...)';
  if (value.signature !== undefined) {
    const ty = signatureTy(value.signature);
    const dropped = ty.k === 'fn' ? ty.params.length - value.params.length : 0;
    return name + showSignature(dropped > 0 ? { ...ty, params: ty.params.slice(dropped) } : ty);
  }
  const params = value.params
    .map((p) => (p.defaultValue === undefined ? p.name : p.name + ' = ...'))
    .join(', ');
  return name + '(' + params + ')';
}

const sections = [];

for (const moduleName of [...STD_MODULES.keys()].sort()) {
  const exports = STD_MODULES.get(moduleName)();
  const names = [...exports.keys()].sort();
  sections.push('### `' + moduleName + '`\n');
  sections.push('```text');
  for (const name of names) {
    sections.push(signature(name, exports.get(name)));
  }
  sections.push('```\n');
}

const generated = [
  BEGIN,
  '',
  '<!-- Generated by scripts/gen-stdlib-docs.mjs — do not edit by hand. -->',
  '',
  ...sections,
  END,
].join('\n');

/** The prelude table, read out of a real interpreter so it cannot go stale. */
function preludeTable() {
  const silent = { writeOut() {}, writeErr() {}, getEnv() { return undefined; }, now() { return 0; } };
  const interpreter = createInterpreter({ host: silent });
  const rows = [];
  for (const name of interpreter.globals.ownNames().sort()) {
    const slot = interpreter.globals.lookup(name);
    const value = slot === undefined ? undefined : slot.value;
    let shown = name;
    let doc = '';
    if (value !== undefined && value.k === 'native') {
      shown = signature(name, value);
      doc = value.doc ?? '';
    } else if (value !== undefined && value.k === 'enumType') {
      doc = 'the `' + name + '` enum type';
    } else if (value !== undefined && value.k === 'enum') {
      doc = 'a value of the `' + value.enumName + '` enum';
    }
    rows.push('| `' + shown + '` | ' + doc + ' |');
  }
  return [
    PRELUDE_BEGIN,
    '',
    '<!-- Generated by scripts/gen-stdlib-docs.mjs — do not edit by hand. -->',
    '',
    '| Name | Meaning |',
    '|---|---|',
    ...rows,
    '',
    PRELUDE_END,
  ].join('\n');
}

const current = readFileSync(DOC, 'utf8');
const start = current.indexOf(BEGIN);
const finish = current.indexOf(END);

if (start === -1 || finish === -1) {
  process.stderr.write('markers not found in ' + DOC + '\n');
  process.exit(1);
}

let next = current.slice(0, start) + generated + current.slice(finish + END.length);

const pStart = next.indexOf(PRELUDE_BEGIN);
const pFinish = next.indexOf(PRELUDE_END);
if (pStart === -1 || pFinish === -1) {
  process.stderr.write('prelude markers not found in ' + DOC + '\n');
  process.exit(1);
}
next = next.slice(0, pStart) + preludeTable() + next.slice(pFinish + PRELUDE_END.length);

if (process.argv.includes('--check')) {
  if (next !== current) {
    process.stderr.write('docs/stdlib.md is out of date — run `node scripts/gen-stdlib-docs.mjs`\n');
    process.exit(1);
  }
  process.stdout.write('docs/stdlib.md is up to date\n');
  process.exit(0);
}

writeFileSync(DOC, next, 'utf8');
process.stdout.write('regenerated the reference in docs/stdlib.md\n');
